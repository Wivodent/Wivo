"""
The invoice PDF's font (send-invoice, send-invoices): Noto Sans regular and
bold, cut down to the letters an Estonian, Latvian or Lithuanian invoice uses,
and kept inside the functions' folder so nothing is fetched while sending.

    python -m pip install fonttools==4.55.3          (in a venv of your own)
    python scripts/invoice-font-subset.py <folder with NotoSans_400Regular.ttf and NotoSans_700Bold.ttf>

Writes supabase/functions/_shared/fonts/NotoSans-{Regular,Bold}-invoice.ttf
(the subsets, regenerable) and supabase/functions/_shared/fonts/invoiceFont.ts
(the same bytes as base64, which the functions import: an import is always in
the deployed bundle, a loose file only if the deploy is told to carry it).
supabase/functions/_shared/fonts/invoiceFont.test.ts checks the two agree and
that every letter below is in both.

The source: Noto Sans (SIL Open Font License 1.1), @expo-google-fonts/noto-sans
0.2.3 on npm. The licence travels in the font's own name table and in
supabase/functions/_shared/fonts/OFL.txt.
"""
import base64
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

# Basic Latin, Latin-1 (ä ö ü õ, €-less), Latin Extended-A (ā č ē ģ ī ķ ļ ņ š ū ž ą ę ė į ų …),
# and the punctuation people paste from Word: dashes, quotes, bullet, ellipsis, euro, numero.
UNICODES = (
    list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x100, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026, 0x20AC, 0x2116]
)

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'supabase' / 'functions' / '_shared' / 'fonts'


def cut(source: Path, target: Path) -> bytes:
    options = subset.Options()
    options.layout_features = []      # pdf-lib places glyphs one by one: no shaping tables needed
    options.hinting = False           # print and screen PDFs do not need TrueType hinting
    options.name_IDs = ['*']          # keep the name table whole: it carries the licence
    options.name_languages = ['*']
    options.notdef_outline = True
    font = TTFont(str(source))
    s = subset.Subsetter(options)
    s.populate(unicodes=UNICODES)
    s.subset(font)
    font.save(str(target))
    return target.read_bytes()


def main() -> None:
    src = Path(sys.argv[1])
    OUT.mkdir(parents=True, exist_ok=True)
    regular = cut(src / 'NotoSans_400Regular.ttf', OUT / 'NotoSans-Regular-invoice.ttf')
    bold = cut(src / 'NotoSans_700Bold.ttf', OUT / 'NotoSans-Bold-invoice.ttf')
    ts = (
        '// GENERATED by scripts/invoice-font-subset.py — do not edit. Noto Sans (SIL OFL 1.1, see OFL.txt),\n'
        '// cut to Latin, Latin-1 and Latin Extended-A: every Estonian, Latvian and Lithuanian letter.\n'
        f'// Regular {len(regular)} bytes, bold {len(bold)} bytes. invoiceFont.test.ts checks these against the .ttf files.\n'
        f"export const NOTO_SANS_REGULAR_B64 = '{base64.b64encode(regular).decode()}'\n"
        f"export const NOTO_SANS_BOLD_B64 = '{base64.b64encode(bold).decode()}'\n"
    )
    (OUT / 'invoiceFont.ts').write_text(ts, encoding='utf-8', newline='\n')
    print(f'regular {len(regular)} B, bold {len(bold)} B, module {len(ts)} B')


if __name__ == '__main__':
    main()
