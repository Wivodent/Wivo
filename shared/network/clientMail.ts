/**
 * The e-mails a clinic sends a Wivo Network client about its orders (the
 * clinic's send-notifications, sql/142 and sql/154), in the client's own
 * language: English, Latvian, Russian or Estonian.
 *
 * A subject line and a link, nothing more: never the message, the reason, an
 * amount, a name or anything about the patient.
 *
 * Most subjects are word for word the notice the client sees in /network
 * (the network.notice* keys in shared/i18n); clientMail.test.ts checks they
 * stay equal in every language. Two differ on purpose: the reminder names no
 * clinic, and the price notice names no amount.
 *
 * Dependency-free: copied into supabase/functions/_shared/generated by
 * scripts/copy-shared-to-functions.mjs.
 */

export type ClientMailLang = 'en' | 'lv' | 'ru' | 'et'
export const CLIENT_MAIL_LANGS: readonly ClientMailLang[] = ['en', 'lv', 'ru', 'et']

export type ClientMailKind =
  | 'message' | 'accepted' | 'rejected' | 'ready' | 'sent' | 'connected' | 'declined'
  | 'received_reminder' | 'problem_resolved' | 'cancelled' | 'reinstated' | 'quoted'

interface MailWords {
  subjects: Record<ClientMailKind, string>
  /** The line before the link. */
  open: string
  /** In place of a reference, when a notice has none. */
  yourOrder: string
}

