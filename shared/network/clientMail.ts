/** The client's language as the clinic knows it; anything else (or none yet) is English. */
export function clientMailLang(v: unknown): ClientMailLang {
  return CLIENT_MAIL_LANGS.includes(v as ClientMailLang) ? v as ClientMailLang : 'en'
}

/** The subject: what happened, which order, which clinic. */
export function clientMailSubject(kind: ClientMailKind, ref: string | null, clinic: string, language: unknown): string {
  const words = CLIENT_MAIL[clientMailLang(language)]
  const subject = words.subjects[kind] ?? words.subjects.message
  return subject.replaceAll('{ref}', ref ?? words.yourOrder).replaceAll('{clinic}', clinic)
}

/** The body: the subject again and the link. */
export function clientMailText(subject: string, link: string, language: unknown): string {
  return `${subject}\n\n${CLIENT_MAIL[clientMailLang(language)].open}: ${link}\n`
}
